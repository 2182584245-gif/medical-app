    @Test public void bundledVoskLoadsAndAcceptsPcmSilenceWithoutMicrophonePermission() throws Exception {
        File modelDirectory = new File(fixture, "vosk-test-model");
        copyAssetTree("vosk-model-small-cn-0.22", modelDirectory);
        assertTrue(new File(modelDirectory, "am/final.mdl").isFile());
        LibVosk.setLogLevel(LogLevel.WARNINGS);
        Model model = new Model(modelDirectory.getAbsolutePath());
        Recognizer recognizer = null;
        try {
            recognizer = new Recognizer(model, 16000.0f);
            byte[] oneSecondSilence = new byte[32000];
            recognizer.acceptWaveForm(oneSecondSilence, oneSecondSilence.length);
            JSONObject result = new JSONObject(recognizer.getFinalResult());
            assertTrue(result.has("text"));
            assertEquals("", result.getString("text").trim());
        } finally {
            if (recognizer != null) recognizer.close();
            model.close();
        }
    }

    private static void writeOcrImage(File destination) throws Exception {
        Bitmap bitmap = Bitmap.createBitmap(1200, 360, Bitmap.Config.ARGB_8888);
        Canvas canvas = new Canvas(bitmap);
        canvas.drawColor(Color.WHITE);
        Paint paint = new Paint(Paint.ANTI_ALIAS_FLAG);
        paint.setColor(Color.BLACK);
        paint.setTypeface(Typeface.create("sans-serif", Typeface.NORMAL));
        paint.setTextSize(72);
        canvas.drawText("检验报告", 60, 110, paint);
        canvas.drawText("血糖  5.5 mmol/L", 60, 235, paint);
        try (OutputStream stream = new FileOutputStream(destination)) {
            assertTrue(bitmap.compress(Bitmap.CompressFormat.PNG, 100, stream));
        } finally {
            bitmap.recycle();
        }
    }

    private void copyAssetTree(String source, File destination) throws Exception {
        String[] children = context.getAssets().list(source);
        if (children != null && children.length > 0) {
            assertTrue(destination.isDirectory() || destination.mkdirs());
            for (String child : children) copyAssetTree(source + "/" + child, new File(destination, child));
        } else {
            try (InputStream input = context.getAssets().open(source); OutputStream output = new FileOutputStream(destination)) {
                byte[] buffer = new byte[65536];
                int count;
                while ((count = input.read(buffer)) != -1) output.write(buffer, 0, count);
            }
        }
    }

    private static byte[] readBytes(File file) throws Exception {
        try (InputStream input = new FileInputStream(file); ByteArrayOutputStream output = new ByteArrayOutputStream()) {
            byte[] buffer = new byte[16384];
            int count;
            while ((count = input.read(buffer)) != -1) output.write(buffer, 0, count);
            return output.toByteArray();
        }
    }
