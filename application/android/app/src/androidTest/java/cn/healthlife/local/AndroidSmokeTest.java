    @Test public void roundTripsAttachmentReportAndDataArchiveAcrossIndependentDirectories() throws Exception {
        member("portable-member");
        File source = new File(fixture, "report.png");
        writeOcrImage(source);
        JSONObject upload = new JSONObject(api.callAttr("import_attachment", source.getAbsolutePath(), "原始报告.png", "血糖 5.5 mmol/L 3.9-6.1").toString());
        assertTrue(upload.toString(), upload.getBoolean("ok"));
        int fileId = upload.getJSONObject("result").getInt("id");
        int reportId = ((Number) good("files.create_report_draft", new JSONObject().put("file_id", fileId)
                .put("report_type", "原文记录").put("report_date", "2026-09-05"))).intValue();
        int itemId = ((Number) good("files.add_report_item_draft", new JSONObject().put("report_id", reportId)
                .put("item_name", "血糖").put("result_value", "5.5").put("unit", "mmol/L")
                .put("reference_range", "3.9-6.1").put("flag", "unknown"))).intValue();
        good("files.confirm_report_item", new JSONObject().put("report_id", reportId).put("item_id", itemId));
        good("files.confirm_report", new JSONObject().put("report_id", reportId));
        File archive = new File(fixture, "transfer.zip");
        JSONObject backup = new JSONObject(api.callAttr("backup_export", archive.getAbsolutePath()).toString());
        assertTrue(backup.toString(), backup.getBoolean("ok"));
        assertTrue(archive.length() > 0);
        initialize(new File(fixture, "second-device"));
        JSONObject imported = new JSONObject(api.callAttr("backup_import", archive.getAbsolutePath()).toString());
        assertTrue(imported.toString(), imported.getBoolean("ok"));
        assertTrue(new File(imported.getJSONObject("result").getString("safety_backup_path")).isFile());
        assertTrue(object("auth.state", new JSONObject()).isNull("user"));
        login("portable-member");
        JSONObject report = object("files.get_report", new JSONObject().put("report_id", reportId));
        assertEquals("confirmed", report.getString("status"));
        assertEquals("血糖", report.getJSONArray("items").getJSONObject(0).getString("item_name"));
        File recovered = new File(fixture, "recovered.png");
        JSONObject exported = new JSONObject(api.callAttr("attachment_export", fileId, recovered.getAbsolutePath()).toString());
        assertTrue(exported.toString(), exported.getBoolean("ok"));
        assertEquals("image/png", exported.getJSONObject("result").getString("media_type"));
        assertArrayEquals(readBytes(source), readBytes(recovered));
        JSONObject check = object("system.check", new JSONObject());
        assertEquals("ok", check.getJSONArray("integrity").getString(0));
        assertEquals(0, check.getInt("foreign_key_errors"));
    }

