def test_frozen_ddl_covers_columns_and_dependencies_in_creation_order():
    created = set()
    for ddl in TABLE_DDL:
        name = re.search(r'CREATE TABLE medical_app_platform\."?(\w+)"?', ddl).group(1)
        references = re.findall(r'\bREFERENCES medical_app_platform\."?(\w+)"?', ddl)
        assert all(ref == name or ref in created for ref in references)
        for column in PLATFORM_COLUMNS[name]:
            assert re.search(rf"\b{column}\s+(?:BIGINT|TEXT|DOUBLE PRECISION|BYTEA|UUID)\b", ddl)
        created.add(name)
    assert created == set(PLATFORM_COLUMNS)
    assert not any(
        "INTEGER PRIMARY KEY" in ddl or "BLOB" in ddl or "instr(" in ddl for ddl in TABLE_DDL
    )
    assert all(
        "GENERATED BY DEFAULT AS IDENTITY" in ddl
        for ddl in TABLE_DDL
        if re.search(r'CREATE TABLE medical_app_platform\."?(\w+)"?', ddl).group(1)
        in IDENTITY_TABLES
    )


