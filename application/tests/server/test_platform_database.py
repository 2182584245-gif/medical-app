def test_rls_every_table_every_policy_and_safe_dependencies():
    rules = policy_rules()
    ddl = "\n".join(policy_ddl())
    assert set(rules) == set(PLATFORM_COLUMNS)
    assert ddl.count("ENABLE ROW LEVEL SECURITY") == 27
    assert ddl.count("FORCE ROW LEVEL SECURITY") == 27
    for statement in policy_ddl():
        if statement.startswith("CREATE POLICY"):
            assert f"current_user = '{PLATFORM_RUNTIME_ROLE}'" in statement
            if " FOR UPDATE " in statement:
                assert " USING " in statement and " WITH CHECK " in statement
    assert "SECURITY DEFINER" not in ddl
    # These are the only RLS cycle roots. They may never reference protected users.
    assert ".users" not in str(rules["advisor_bindings"])
    assert ".users" not in str(rules["product_recommendations"])
    assert ".users" not in str(rules["orders"])
    assert "auth_username" in str(rules["users"])
    assert "registering" in str(rules["conversations"])
    assert "role_code = current_setting" in rules["users"]["UPDATE"][1]
    assert "account_status = 'active'" in rules["users"]["UPDATE"][1]


