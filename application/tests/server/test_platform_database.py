def test_constraint_errors_keep_compatibility_but_not_raw_secrets(database):
    original = SimpleNamespace(sqlstate="23505")
    database.engine.error = IntegrityError("SECRET SQL", {"password": "SECRET"}, original)
    with pytest.raises(sqlite3.IntegrityError) as error, database.transaction() as connection:
        connection.execute("INSERT INTO users(username) VALUES (?)", ("SECRET",))
    assert "SECRET" not in str(error.value)
    assert error.value.sqlstate == "23505"
    assert ("rollback", ()) in database.engine.log


def test_initialize_only_reads_shape_and_forced_probe_rechecks(database):
    from server.platform_experience_schema import PLATFORM_COLUMNS as current_columns
    database.initialize()

    def count():
        return sum("LIMIT 0" in sql for sql, _ in database.engine.log)

    assert count() == len(current_columns)
    database.initialize()
    assert count() == len(current_columns)
    database.initialize(force=True)
    assert count() == 2 * len(current_columns)
    assert not any(re.match(r"(?:CREATE|ALTER|INSERT)\b", sql) for sql, _ in database.engine.log)
    with pytest.raises(RuntimeError, match="no local SQLite"):
        _ = database.path
    database.dispose()
    assert database.engine.log[-1][0] == "dispose"


