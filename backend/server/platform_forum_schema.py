"""Reviewed additive schema for the member experience forum."""

from .platform_schema import ACTOR_ID, PLATFORM_RUNTIME_ROLE, PLATFORM_SCHEMA, RUNTIME, SIGNED_IN

FORUM_TABLES = ("forum_topics", "forum_posts", "forum_likes", "forum_comments")

TABLE_DDL = (
    f"""CREATE TABLE {PLATFORM_SCHEMA}.forum_topics (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        slug TEXT NOT NULL UNIQUE CHECK(length(slug) BETWEEN 1 AND 80),
        name TEXT NOT NULL UNIQUE CHECK(length(name) BETWEEN 1 AND 80),
        created_at TEXT NOT NULL, updated_at TEXT NOT NULL
    )""",
    f"""CREATE TABLE {PLATFORM_SCHEMA}.forum_posts (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        topic_id BIGINT NOT NULL REFERENCES {PLATFORM_SCHEMA}.forum_topics(id) ON DELETE CASCADE,
        author_user_id BIGINT NOT NULL REFERENCES {PLATFORM_SCHEMA}.users(id) ON DELETE CASCADE,
        content TEXT NOT NULL CHECK(length(content) BETWEEN 1 AND 4000),
        status TEXT NOT NULL CHECK(status IN ('active','hidden')),
        created_at TEXT NOT NULL, updated_at TEXT NOT NULL
    )""",
    f"""CREATE TABLE {PLATFORM_SCHEMA}.forum_likes (
        post_id BIGINT NOT NULL REFERENCES {PLATFORM_SCHEMA}.forum_posts(id) ON DELETE CASCADE,
        user_id BIGINT NOT NULL REFERENCES {PLATFORM_SCHEMA}.users(id) ON DELETE CASCADE,
        created_at TEXT NOT NULL, PRIMARY KEY(post_id, user_id)
    )""",
    f"""CREATE TABLE {PLATFORM_SCHEMA}.forum_comments (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        post_id BIGINT NOT NULL REFERENCES {PLATFORM_SCHEMA}.forum_posts(id) ON DELETE CASCADE,
        author_user_id BIGINT NOT NULL REFERENCES {PLATFORM_SCHEMA}.users(id) ON DELETE CASCADE,
        content TEXT NOT NULL CHECK(length(content) BETWEEN 1 AND 4000),
        created_at TEXT NOT NULL
    )""",
)

INDEX_DDL = (
    f"CREATE INDEX idx_forum_posts_topic_time ON {PLATFORM_SCHEMA}.forum_posts(topic_id, created_at DESC, id DESC)",
    f"CREATE INDEX idx_forum_likes_user ON {PLATFORM_SCHEMA}.forum_likes(user_id)",
    f"CREATE INDEX idx_forum_comments_post_time ON {PLATFORM_SCHEMA}.forum_comments(post_id, created_at DESC)",
)


def policy_ddl() -> tuple[str, ...]:
    own_post = f"author_user_id = {ACTOR_ID}"
    own_comment = f"author_user_id = {ACTOR_ID}"
    own_like = f"user_id = {ACTOR_ID}"
    return (
        *(f"ALTER TABLE {PLATFORM_SCHEMA}.{table} ENABLE ROW LEVEL SECURITY" for table in FORUM_TABLES),
        *(f"ALTER TABLE {PLATFORM_SCHEMA}.{table} FORCE ROW LEVEL SECURITY" for table in FORUM_TABLES),
        f"CREATE POLICY forum_topic_read ON {PLATFORM_SCHEMA}.forum_topics FOR SELECT TO PUBLIC USING ({RUNTIME} AND {SIGNED_IN})",
        f"CREATE POLICY forum_topic_write ON {PLATFORM_SCHEMA}.forum_topics FOR ALL TO PUBLIC USING ({RUNTIME} AND {RUNTIME} AND current_setting('medical_app.role_code', true) = 'operator') WITH CHECK ({RUNTIME} AND current_setting('medical_app.role_code', true) = 'operator')",
        f"CREATE POLICY forum_post_read ON {PLATFORM_SCHEMA}.forum_posts FOR SELECT TO PUBLIC USING ({RUNTIME} AND {SIGNED_IN} AND status = 'active')",
        f"CREATE POLICY forum_post_insert ON {PLATFORM_SCHEMA}.forum_posts FOR INSERT TO PUBLIC WITH CHECK ({RUNTIME} AND {SIGNED_IN} AND {own_post})",
        f"CREATE POLICY forum_post_update ON {PLATFORM_SCHEMA}.forum_posts FOR UPDATE TO PUBLIC USING ({RUNTIME} AND ({own_post} OR current_setting('medical_app.role_code', true) = 'operator')) WITH CHECK ({RUNTIME} AND ({own_post} OR current_setting('medical_app.role_code', true) = 'operator'))",
        f"CREATE POLICY forum_post_delete ON {PLATFORM_SCHEMA}.forum_posts FOR DELETE TO PUBLIC USING ({RUNTIME} AND ({own_post} OR current_setting('medical_app.role_code', true) = 'operator'))",
        f"CREATE POLICY forum_like_read ON {PLATFORM_SCHEMA}.forum_likes FOR SELECT TO PUBLIC USING ({RUNTIME} AND {SIGNED_IN})",
        f"CREATE POLICY forum_like_insert ON {PLATFORM_SCHEMA}.forum_likes FOR INSERT TO PUBLIC WITH CHECK ({RUNTIME} AND {SIGNED_IN} AND {own_like})",
        f"CREATE POLICY forum_like_delete ON {PLATFORM_SCHEMA}.forum_likes FOR DELETE TO PUBLIC USING ({RUNTIME} AND {own_like})",
        f"CREATE POLICY forum_comment_read ON {PLATFORM_SCHEMA}.forum_comments FOR SELECT TO PUBLIC USING ({RUNTIME} AND {SIGNED_IN})",
        f"CREATE POLICY forum_comment_insert ON {PLATFORM_SCHEMA}.forum_comments FOR INSERT TO PUBLIC WITH CHECK ({RUNTIME} AND {SIGNED_IN} AND {own_comment})",
        f"CREATE POLICY forum_comment_update ON {PLATFORM_SCHEMA}.forum_comments FOR UPDATE TO PUBLIC USING ({RUNTIME} AND {own_comment}) WITH CHECK ({RUNTIME} AND {own_comment})",
        f"CREATE POLICY forum_comment_delete ON {PLATFORM_SCHEMA}.forum_comments FOR DELETE TO PUBLIC USING ({RUNTIME} AND {own_comment})",
    )


def grant_ddl() -> tuple[str, ...]:
    return (
        f"GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE {PLATFORM_SCHEMA}.forum_topics TO {PLATFORM_RUNTIME_ROLE}",
        f"GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE {PLATFORM_SCHEMA}.forum_posts TO {PLATFORM_RUNTIME_ROLE}",
        f"GRANT SELECT, INSERT, DELETE ON TABLE {PLATFORM_SCHEMA}.forum_likes TO {PLATFORM_RUNTIME_ROLE}",
        f"GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE {PLATFORM_SCHEMA}.forum_comments TO {PLATFORM_RUNTIME_ROLE}",
        f"GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA {PLATFORM_SCHEMA} TO {PLATFORM_RUNTIME_ROLE}",
    )

